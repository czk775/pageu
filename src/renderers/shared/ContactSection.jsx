import { useEffect, useRef, useState } from 'react';
import { Mail, Phone } from 'lucide-react';
import { StatusToast } from '../../components/StatusToast';
import { AnimatedSection } from './PortfolioMotionContext';

const copyText = async (value) => {
  if (!value || typeof navigator === 'undefined' || !navigator.clipboard?.writeText) {
    return;
  }

  await navigator.clipboard.writeText(value);
};

export function ContactSection({ siteDraft, variant = 'default' }) {
  const [toastMessage, setToastMessage] = useState('');
  const toastTimer = useRef(null);
  const profile = siteDraft.profile || {};
  const contact = siteDraft.contact || {};
  const email = profile.email || contact.email || '';
  const phone = profile.phone || contact.phone || '';
  const showCopyToast = async (value) => {
    await copyText(value);
    if (toastTimer.current) {
      window.clearTimeout(toastTimer.current);
    }
    setToastMessage('');
    window.setTimeout(() => {
      setToastMessage('复制成功');
      toastTimer.current = window.setTimeout(() => setToastMessage(''), 1000);
    }, 0);
  };

  useEffect(
    () => () => {
      if (toastTimer.current) {
        window.clearTimeout(toastTimer.current);
      }
    },
    [],
  );

  return (
    <AnimatedSection id="contact" motionKey="contact" className={`portfolio-contact-section portfolio-contact-${variant}`} aria-label="Contact" delay={0.1}>
      <p className="portfolio-section-eyebrow">Contact</p>
      <div className="portfolio-contact-panel">
        <div className="portfolio-contact-copy">
          <h2>联系我</h2>
          <p>如果你对我的经历或项目感兴趣，欢迎联系我。</p>
        </div>
        <div className="portfolio-contact-methods">
          <article className="portfolio-contact-method">
            <span>
              <Mail size={17} />
              邮箱
            </span>
            <strong>{email || '暂未填写'}</strong>
            <button type="button" disabled={!email} onClick={() => showCopyToast(email)}>
              复制邮箱
            </button>
          </article>
          <article className="portfolio-contact-method">
            <span>
              <Phone size={17} />
              手机号
            </span>
            <strong>{phone || '暂未填写'}</strong>
            <button type="button" disabled={!phone} onClick={() => showCopyToast(phone)}>
              复制手机号
            </button>
          </article>
        </div>
      </div>
      <footer className="generated-footer">Generated by PageU</footer>
      <StatusToast message={toastMessage} />
    </AnimatedSection>
  );
}
