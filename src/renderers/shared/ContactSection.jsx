export function ContactSection({ siteDraft, variant = 'default' }) {
  const profile = siteDraft.profile || {};
  const contact = siteDraft.contact || {};
  const directContact = profile.contact || contact.email || contact.phone || '';

  return (
    <section id="contact" className={`portfolio-contact-section portfolio-contact-${variant}`} aria-label="Contact">
      <p className="portfolio-section-eyebrow">Contact</p>
      <div className="portfolio-contact-panel">
        <div>
          <h2>联系我</h2>
          <p>{directContact || '欢迎通过作品链接或简历继续了解我。'}</p>
        </div>
        <div className="portfolio-contact-actions">
          {directContact ? <a href={directContact.includes('@') ? `mailto:${directContact}` : '#contact'}>发送消息</a> : null}
          {(contact.links || []).slice(0, 3).map((link) => (
            <a key={link.url} href={link.url} target="_blank" rel="noreferrer">
              {link.title}
            </a>
          ))}
        </div>
      </div>
      <footer className="generated-footer">Generated by PageU</footer>
    </section>
  );
}
