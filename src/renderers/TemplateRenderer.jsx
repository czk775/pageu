import { motion } from 'framer-motion';
import { templates } from '../data/templates';
import { normalizeSiteDraft } from '../types/siteDraft';

const templateIds = new Set(templates.map((template) => template.id));

const getVisibleSections = (siteDraft) =>
  siteDraft.sections.filter((section) => section.visible && !section.collapsed && section.type !== 'avatar' && section.type !== 'intro');

const renderSectionBody = (section) => {
  if (section.type === 'skills') {
    return (
      <div className="generated-skills">
        {section.items.map((item) => (
          <span key={item.id}>{item.title}</span>
        ))}
      </div>
    );
  }

  if (section.items.length > 0) {
    return (
      <div className="generated-items">
        {section.items.map((item) => (
          <article key={item.id}>
            <h3>{item.title}</h3>
            {item.description ? <p>{item.description}</p> : null}
          </article>
        ))}
      </div>
    );
  }

  return <p>{section.content || '这部分内容正在整理中。'}</p>;
};

export function TemplateRenderer({ siteDraft, as: Surface = 'article', previewMode = 'desktop', className = '' }) {
  const normalizedDraft = normalizeSiteDraft(siteDraft);
  const template = templateIds.has(normalizedDraft.template) ? normalizedDraft.template : 'neo';
  const visibleSections = getVisibleSections(normalizedDraft);
  const initial = previewMode === 'mobile' ? { opacity: 0, y: 12 } : { opacity: 0, y: 18 };

  return (
    <Surface
      className={`generated-site template-${template}-site ${previewMode === 'mobile' ? 'generated-site-mobile' : ''} ${className}`}
      data-template={template}
      style={{
        '--generated-primary': normalizedDraft.theme.primaryColor,
        '--generated-bg': normalizedDraft.theme.background,
        '--generated-text': normalizedDraft.theme.textColor,
      }}
    >
      <section className="generated-hero" aria-label="个人主页首屏">
        <motion.div
          className="generated-avatar"
          aria-hidden="true"
          initial={{ scale: 0.88, opacity: 0 }}
          animate={{ scale: 1, opacity: 1 }}
          transition={{ duration: 0.48, ease: 'easeOut' }}
        >
          {normalizedDraft.profile.name.slice(0, 1) || 'U'}
        </motion.div>
        <motion.div
          className="generated-hero-copy"
          initial={initial}
          animate={{ opacity: 1, y: 0 }}
          transition={{ duration: 0.56, ease: 'easeOut' }}
        >
          <p>{normalizedDraft.profile.targetRole}</p>
          <h1>{normalizedDraft.profile.name}</h1>
          <strong>{normalizedDraft.profile.headline}</strong>
          <span>{normalizedDraft.profile.intro}</span>
        </motion.div>
      </section>

      <section className="generated-section-wrap" aria-label="个人网站内容">
        {visibleSections.map((section, index) => (
          <motion.section
            className={`generated-section generated-section-${section.type}`}
            key={section.id}
            initial={{ opacity: 0, y: 18 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ duration: 0.42, delay: index * 0.04, ease: 'easeOut' }}
          >
            <div className="generated-section-title">
              <span>{String(index + 1).padStart(2, '0')}</span>
              <h2>{section.title}</h2>
            </div>
            {renderSectionBody(section)}
          </motion.section>
        ))}
      </section>

      <footer className="generated-footer">Generated by PageU</footer>
    </Surface>
  );
}
